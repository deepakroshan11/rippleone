import type { Project, Layer, TextLayer, ImageLayer, ShapeLayer } from '@/types/project';

/**
 * Generates a React component from a Project JSON.
 * Deterministic — not LLM-generated.
 */
export function generateReact(project: Project): string {
  const componentName = toComponentName(project.name);
  const { canvas, duration, background, layers } = project;

  const imports = `import React, { useEffect, useRef, useState } from 'react';`;

  const layerComponents = layers.map(layer => generateLayerComponent(layer)).join('\n\n');

  const bgStyle = getBackgroundStyle(project);

  const component = `${imports}

// Generated by RippleOne
// Project: ${project.name}
// Duration: ${duration}ms
// Canvas: ${canvas.width}x${canvas.height}

${layerComponents}

/**
 * ${componentName} — Animated splash screen component
 * Generated from RippleOne Project JSON v${project.version}
 *
 * Browser Support: Chrome, Firefox, Safari (latest 2 versions)
 * Required: CSS animations, requestAnimationFrame
 */
export function ${componentName}({ onComplete, scale = 1 }: { onComplete?: () => void; scale?: number }) {
  const [time, setTime] = useState(0);
  const rafRef = useRef<number | null>(null);
  const startRef = useRef<number | null>(null);

  useEffect(() => {
    const animate = (ts: number) => {
      if (!startRef.current) startRef.current = ts;
      const elapsed = ts - startRef.current;
      setTime(elapsed);

      if (elapsed < ${duration}) {
        rafRef.current = requestAnimationFrame(animate);
      } else {
        setTime(${duration});
        onComplete?.();
      }
    };

    rafRef.current = requestAnimationFrame(animate);
    return () => { if (rafRef.current) cancelAnimationFrame(rafRef.current); };
  }, [onComplete]);

  const canvasStyle: React.CSSProperties = {
    width: ${canvas.width} * scale,
    height: ${canvas.height} * scale,
    position: 'relative',
    overflow: 'hidden',
    ${bgStyle}
  };

  return (
    <div style={canvasStyle} role="img" aria-label="${project.name} intro animation">
${layers.map(l => `      <${toComponentName(l.name)}_Layer time={time} scale={scale} />`).join('\n')}
    </div>
  );
}

export default ${componentName};
`;

  return component;
}

function generateLayerComponent(layer: Layer): string {
  const name = `${toComponentName(layer.name)}_Layer`;
  const { start, duration: dur, easing = 'ease' } = layer.timeline;
  const enterDur = layer.animation?.enterDuration || 600;
  const exitDur = layer.animation?.exitDuration || 400;

  return `function ${name}({ time, scale }: { time: number; scale: number }) {
  const start = ${start};
  const duration = ${dur};
  const end = start + duration;
  const enterDur = ${enterDur};
  const exitDur = ${exitDur};

  if (time < start || time > end) return null;

  const elapsed = time - start;
  const timeLeft = end - time;
  const enterProgress = Math.min(1, elapsed / enterDur);
  const exitProgress = Math.min(1, Math.max(0, 1 - timeLeft / exitDur));

  let opacity = ${layer.opacity ?? 1} * Math.min(enterProgress, 1 - exitProgress + (timeLeft > exitDur ? 1 : 0));
  opacity = Math.max(0, Math.min(1, opacity));

  const style: React.CSSProperties = {
    position: 'absolute',
    left: ${layer.position.x} * scale,
    top: ${layer.position.y} * scale,
    transform: \`translate(-50%, -50%) translateY(\${${layer.animation?.enter === 'slideUp' ? '(1 - enterProgress) * 40' : '0'} * scale}px)\`,
    opacity,
    ${layer.size ? `width: ${layer.size.width} * scale, height: ${layer.size.height} * scale,` : ''}
    ${getTypeStylesReact(layer)}
  };

  return <div style={style}>${getLayerContent(layer)}</div>;
}`;
}

function getTypeStylesReact(layer: Layer): string {
  if (layer.type === 'text') {
    const tl = layer as TextLayer;
    return `fontFamily: '${tl.props.fontFamily}',
    fontSize: \`\${${tl.props.fontSize} * scale}px\`,
    fontWeight: ${tl.props.fontWeight},
    color: '${tl.props.color}',
    textAlign: '${tl.props.align}',
    whiteSpace: 'nowrap',
    ${tl.props.textShadow ? `textShadow: '${tl.props.textShadow}',` : ''}`;
  }
  if (layer.type === 'shape') {
    const sl = layer as ShapeLayer;
    return `background: '${sl.props.fill}',
    ${sl.props.variant === 'circle' ? "borderRadius: '50%'," : ''}`;
  }
  return '';
}

function getLayerContent(layer: Layer): string {
  if (layer.type === 'text') {
    return (layer as TextLayer).props.content;
  }
  if (layer.type === 'image') {
    const il = layer as ImageLayer;
    return `<img src="${il.props.src}" alt="${il.props.alt || layer.name}" style={{ width: '100%', height: '100%', objectFit: '${il.props.objectFit || 'contain'}' }} />`;
  }
  return '';
}

function getBackgroundStyle(project: Project): string {
  const bg = project.background;
  if (bg.type === 'solid') return `background: '${bg.color}',`;
  if (bg.type === 'gradient') {
    if (bg.direction === 'radial') {
      const stops = bg.stops.map(s => `${s.color} ${s.position}%`).join(', ');
      return `background: 'radial-gradient(circle, ${stops})',`;
    }
    const dir = bg.direction === 'to-bottom' ? 'to bottom' : 'to right';
    const stops = bg.stops.map(s => `${s.color} ${s.position}%`).join(', ');
    return `background: 'linear-gradient(${dir}, ${stops})',`;
  }
  return `background: '#000',`;
}

function toComponentName(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9\s]/g, '')
    .split(/\s+/)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join('');
}
