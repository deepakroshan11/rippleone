export function getTemplateBySlug(slug: string): StaticTemplate | undefined {
  return STATIC_TEMPLATES.find(t => t.slug === slug);
}

export function getTemplatesByCategory(category: string): StaticTemplate[] {
  if (category === 'All') return STATIC_TEMPLATES;
  return STATIC_TEMPLATES.filter(t => t.category === category);
}

export function getFeaturedTemplates(): StaticTemplate[] {
  return STATIC_TEMPLATES.filter(t => t.isFeatured);
}
